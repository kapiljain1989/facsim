def _write_csv(path: Path, rows: Iterable[dict[str, Any]]) -> int:
    rows = list(rows)
    if not rows:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("")
        return 0
    columns: list[str] = []
    for row in rows:
        for key in row:
            if key not in columns:
                columns.append(key)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
    return len(rows)


def _write_readme(path: Path, out: StudyOutput, config, written: dict[str, int], seed: int) -> None:
    """Dataset card, with every figure taken from this run."""
    # The example should be a patient with a decent number of visits.
    per_subject: dict[str, int] = {}
    for row in out.tr:
        per_subject[row["USUBJID"]] = per_subject.get(row["USUBJID"], 0) + 1
    example = max(per_subject, key=lambda key: per_subject[key]) if per_subject else ""
    path.write_text(
        _README.format(
            study_id=out.study_id,
            subjects=len(out.subjects),
            arms=len(config.protocol.arms),
            cutoff=config.protocol.analysis.cutoff_weeks_from_fsi,
            n_subjects=f"{written.get('subjects', 0):,}",
            n_tu=f"{written.get('tu', 0):,}",
            n_tr=f"{written.get('tr', 0):,}",
            n_rs=f"{written.get('rs', 0):,}",
            n_adtte=f"{written.get('adtte', 0):,}",
            n_truth=f"{written.get('truth', 0):,}",
            seed=seed,
            example_subject=example,
        )
    )


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--config", default="config/clinical")
    parser.add_argument("--output", default="data/clinical")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    started = time.monotonic()
    config = load_clinical_config(args.config)
    print(f"running {config.protocol.study_id}")
    out = run_study(config, seed=args.seed)
    print(out.summary())

    root = Path(args.output)
    written = {name: _write_csv(root / f"{name}.csv", getattr(out, name)) for name in _OPERATIONAL}
    # Ground truth to its own directory, so globbing the operational data cannot
    # pick it up.
    written["truth"] = _write_csv(root / "truth" / "tumour_parameters.csv", out.truth)

    _write_readme(root / "README.md", out, config, written, args.seed)
    (root / "manifest.json").write_text(
        json.dumps(
            {
                "study_id": out.study_id,
                "seed": args.seed,
                "config": args.config,
                "tables": written,
            },
            indent=2,
        )
        + "\n"
    )

    print(f"\nwritten to {root}")
    for name, count in written.items():
        label = "truth/tumour_parameters.csv" if name == "truth" else f"{name}.csv"
        print(f"  {label:<30} {count:>8,} rows")
    print(f"\nelapsed {time.monotonic() - started:,.1f} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
