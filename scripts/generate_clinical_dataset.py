def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--config", default="config/clinical")
    parser.add_argument("--output", default="data/clinical")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--lifecycle", default="config/lifecycle",
        help="lifecycle links directory",
    )
    parser.add_argument(
        "--manufacturing-export",
        help="a plant export directory. Given one, every kit traces to a batch the "
             "plant actually released; without one the spine uses labelled stubs",
    )
    args = parser.parse_args()

    started = time.monotonic()
    config = load_clinical_config(args.config)
    lifecycle = load_lifecycle_config(args.lifecycle)
    print(f"running {config.protocol.study_id}")
    out = run_study(
        config,
        lifecycle,
        seed=args.seed,
        manufacturing_export=args.manufacturing_export,
    )
    print(out.summary())

    report = verify_spine(out, lifecycle)
    print()
    print(report.render())
    if not report.ok:
        print("\nthe identity graph does not hold; not writing a dataset", file=sys.stderr)
        return 1

    root = Path(args.output)
    written = {
        name: _write_csv(root / f"{name}.csv", getattr(out, name))
        for name in (*_OPERATIONAL, "tmf_documents")
    }
    # Ground truth to its own directory, so globbing the operational data cannot
    # pick it up.
    written["truth"] = _write_csv(root / "truth" / "tumour_parameters.csv", out.truth)

    _write_readme(root / "README.md", out, config, written, args.seed)
    (root / "manifest.json").write_text(
        json.dumps(
            {
                "study_id": out.study_id,
                "seed": args.seed,
                "config": args.config,
                "tables": written,
            },
            indent=2,
        )
        + "\n"
    )

    print(f"\nwritten to {root}")
    for name, count in written.items():
        label = "truth/tumour_parameters.csv" if name == "truth" else f"{name}.csv"
        print(f"  {label:<30} {count:>8,} rows")
    print(f"\nelapsed {time.monotonic() - started:,.1f} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
